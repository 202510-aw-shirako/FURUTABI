package com.furutabi.app;

public class AppProfileForm {

    private String bio;
    private String region;
    private String interestRegion;
    private String visitHistory;
    private String careNote;
    private String withChildren;
    private String foodNote;
    private String relationNote;

    public String getBio() {
        return bio;
    }

    public void setBio(String bio) {
        this.bio = bio;
    }

    public String getRegion() {
        return region;
    }

    public void setRegion(String region) {
        this.region = region;
    }

    public String getInterestRegion() {
        return interestRegion;
    }

    public void setInterestRegion(String interestRegion) {
        this.interestRegion = interestRegion;
    }

    public String getVisitHistory() {
        return visitHistory;
    }

    public void setVisitHistory(String visitHistory) {
        this.visitHistory = visitHistory;
    }

    public String getCareNote() {
        return careNote;
    }

    public void setCareNote(String careNote) {
        this.careNote = careNote;
    }

    public String getWithChildren() {
        return withChildren;
    }

    public void setWithChildren(String withChildren) {
        this.withChildren = withChildren;
    }

    public String getFoodNote() {
        return foodNote;
    }

    public void setFoodNote(String foodNote) {
        this.foodNote = foodNote;
    }

    public String getRelationNote() {
        return relationNote;
    }

    public void setRelationNote(String relationNote) {
        this.relationNote = relationNote;
    }
}
